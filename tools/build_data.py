#!/usr/bin/env python3
"""Bundle data/*.json into data/bundle.js so the site also works from file://.

Run after every change to data/*.json:  python3 tools/build_data.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
PARTS = ["questions", "clusters", "topics", "fact_groups"]


def main():
    raw = {}
    for name in PARTS:
        with open(DATA / f"{name}.json", encoding="utf-8") as f:
            raw[name] = json.load(f)
    payload = json.dumps(
        {
            "questions": raw["questions"],
            "clusters": raw["clusters"],
            "topics": raw["topics"],
            "groups": raw["fact_groups"],
        },
        ensure_ascii=False,
        separators=(",", ":"),
    )
    out = DATA / "bundle.js"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/build_data.py from data/*.json – do not edit\n")
        f.write(f"window.MBP_RAW = {payload};\n")
    print(f"wrote {out.relative_to(ROOT)} ({len(raw['questions'])} questions, "
          f"{len(raw['clusters'])} clusters, {len(raw['topics'])} topics, "
          f"{len(raw['fact_groups'])} groups)")


if __name__ == "__main__":
    main()
